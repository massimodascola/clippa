import AppKit
import ClippaCore
import ClippaPasteboard

/// Watches the system clipboard and turns every new copy into a
/// `CapturedContent`. macOS has no "clipboard changed" notification, so
/// like every clipboard manager it checks the change counter a few times a
/// second (a cheap call that reads no content).
@MainActor
final class ClipboardMonitor {
    private let pasteboard = DebugHooks.pasteboard
    private var lastChangeCount: Int
    private var timer: Timer?
    private let onCapture: (RawCapture) -> Void

    /// Formats bigger than this are not saved (the others of the same copy are).
    private let maxRepresentationSize = 30 * 1024 * 1024
    /// Above this a whole copy keeps only its main formats.
    nonisolated static let maxTotalSize = 60 * 1024 * 1024

    /// What was read from the clipboard, before the slow work (thumbnails,
    /// image conversion), which `process` does off the main thread.
    struct RawCapture: Sendable {
        var representations: [CapturedRepresentation]
        var text: String
        var fileURLs: [URL]
        var sourceID: String?
        var sourceName: String?
        /// Dictated, not copied: saved without the copy sound.
        var isDictation = false
        /// When it reached the clipboard, if it is saved later.
        var copiedAt: Date?
    }

    /// Copies made on another device are read on this queue: their data
    /// comes over the air on first read, which can take seconds.
    private let remoteQueue = DispatchQueue(label: "clippa.remote-clipboard", qos: .utility)
    /// What is on the clipboard now (its text, or its formats), when known:
    /// Wispr Flow puts it back after a dictation.
    private var currentContent: String?
    private var contentBeforeLastChange: String?
    /// After a Wispr Flow dictation: what was on the clipboard before it,
    /// which Wispr Flow puts back, until when.
    private var wisprRestore: (content: String?, until: Date)?
    private let wisprQueue = DispatchQueue(label: "clippa.wispr-flow", qos: .utility)
    /// When the latest dictation reached the clipboard, and its text once saved.
    private var lastWisprWrite = Date.distantPast
    private var lastWisprText: String?
    /// The newest dictation taken from Wispr Flow's history.
    private var lastWisprDictation: String {
        get { UserDefaults.standard.string(forKey: "lastWisprDictation") ?? "" }
        set { UserDefaults.standard.set(newValue, forKey: "lastWisprDictation") }
    }

    init(onCapture: @escaping (RawCapture) -> Void) {
        self.onCapture = onCapture
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        timer?.invalidate()
        let timer = Timer(timeInterval: 0.3, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    var isPaused: Bool {
        guard let until = Pref.pausedUntilDate else { return false }
        if until > Date() { return true }
        Pref.pausedUntilDate = nil
        return false
    }

    private func check() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        guard !isPaused, let items = pasteboard.pasteboardItems, !items.isEmpty else {
            currentContent = nil
            return
        }
        let allTypes = Set(items.flatMap { $0.types.map(\.rawValue) })
        let before = currentContent
        contentBeforeLastChange = before
        let isLocal = !allTypes.contains(UTI.remoteClipboard)
        currentContent = isLocal && !allTypes.contains(UTI.concealed)
            ? Self.contentKey(types: allTypes, text: pasteboard.string(forType: .string)) : nil
        if let restore = wisprRestore, Date() < restore.until, let now = currentContent, now == restore.content {
            // What was there before the dictation, put back by Wispr Flow:
            // already saved, and moving it to the front would hide the dictation.
            wisprRestore = nil
            Log.info("Copy ignored: Wispr Flow put the clipboard back")
            return
        }
        if !isLocal {
            // Passwords copied on the iPhone are marked like on the Mac.
            let defaults = UserDefaults.standard
            if defaults.bool(forKey: Pref.ignoreConfidential), allTypes.contains(UTI.concealed) {
                Log.info("Copy from another device ignored: marked confidential")
            } else if defaults.bool(forKey: Pref.ignoreTransient),
                      allTypes.contains(UTI.transient) || allTypes.contains(UTI.autoGenerated) {
                return
            } else {
                readRemote(changeCount: count)
            }
        } else if let content = read(items, types: allTypes) {
            deliver(content)
        }
    }

    private func deliver(_ content: RawCapture) {
        onCapture(content)
    }

    /// Identifies a clipboard's content well enough to recognize it when it
    /// comes back: its text, or the list of its formats.
    nonisolated static func contentKey(types: Set<String>, text: String?) -> String? {
        if let text, !text.isEmpty { return "text:" + text }
        let formats = types.filter {
            !$0.hasPrefix("org.nspasteboard.") && $0 != UTI.remoteClipboard && $0 != PasteboardWriter.ownType.rawValue
        }
        return formats.isEmpty ? nil : "types:" + formats.sorted().joined(separator: ",")
    }

    /// Reads the clipboard now, applying the privacy rules. Returns nil when
    /// the copy must be ignored.
    private func read(_ items: [NSPasteboardItem], types allTypes: Set<String>) -> RawCapture? {
        // Clippa's own writes.
        if allTypes.contains(PasteboardWriter.ownType.rawValue) { return nil }
        let defaults = UserDefaults.standard
        if allTypes.contains(UTI.concealed), defaults.bool(forKey: Pref.ignoreConfidential) {
            if WisprFlow.mightBeDictation(allTypes) {
                takeWisprDictation(before: contentBeforeLastChange)
            } else {
                Log.info("Copy ignored: marked confidential")
            }
            return nil
        }
        if defaults.bool(forKey: Pref.ignoreTransient),
           allTypes.contains(UTI.transient) || allTypes.contains(UTI.autoGenerated) { return nil }

        // The app that copied: the one in front, unless the copy names its source.
        var sourceID = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        var sourceName = NSWorkspace.shared.frontmostApplication?.localizedName
        if let declared = items.first?.string(forType: NSPasteboard.PasteboardType(UTI.source)), !declared.isEmpty {
            sourceID = declared
            sourceName = AppIcons.name(for: declared)
        }
        if let restore = wisprRestore, Date() < restore.until, let dictated = lastWisprText,
           pasteboard.string(forType: .string) == dictated {
            // Wispr Flow left the dictation on the clipboard (nothing took the paste).
            sourceID = WisprFlow.bundleID
            sourceName = "Wispr Flow"
        }
        if let sourceID, Pref.ignoredAppIDs.contains(sourceID) {
            Log.info("Copy ignored: app in the ignore list")
            return nil
        }

        // Read every format of every pasteboard item.
        var representations: [CapturedRepresentation] = []
        for (index, item) in items.enumerated() {
            for type in item.types {
                let raw = type.rawValue
                if raw.hasPrefix("org.nspasteboard.") || raw == PasteboardWriter.ownType.rawValue { continue }
                guard let data = item.data(forType: type), data.count <= maxRepresentationSize else { continue }
                representations.append(CapturedRepresentation(index: index, type: raw, data: data))
            }
        }
        guard !representations.isEmpty else { return nil }

        let fileURLs = items.compactMap { $0.string(forType: .fileURL).flatMap(URL.init(string:)) }
        // HTML parsing must happen on the main thread, so the text is read here.
        let text = pasteboard.string(forType: .string) ?? Self.textFromFormatted(representations) ?? ""
        return RawCapture(representations: representations, text: text, fileURLs: fileURLs,
                          sourceID: sourceID, sourceName: sourceName)
    }

    /// A confidential copy while Wispr Flow is running: probably a
    /// dictation. The clipboard is left alone (see WisprFlow); the dictation
    /// is taken from Wispr Flow's history, which may record it a moment later.
    private func takeWisprDictation(before: String?) {
        let started = Date()
        lastWisprWrite = started
        wisprRestore = (before, started.addingTimeInterval(10))
        if lastWisprDictation.isEmpty { lastWisprDictation = WisprFlow.timestamp(started.addingTimeInterval(-60)) }
        // Dictations started up to 30 minutes ago (long ones) count.
        let notBefore = WisprFlow.timestamp(started.addingTimeInterval(-1800))
        let delays: [TimeInterval] = [0.3, 1, 2.5, 5, 9]
        for (attempt, delay) in delays.enumerated() {
            let isLast = attempt == delays.count - 1
            wisprQueue.asyncAfter(deadline: .now() + delay) { [weak self] in
                guard let self else { return }
                let after = DispatchQueue.main.sync { MainActor.assumeIsolated { self.lastWisprDictation } }
                guard let found = WisprFlow.dictations(after: after, notBefore: notBefore) else {
                    if isLast { Log.warning("Wispr Flow dictation: its history could not be read") }
                    return
                }
                DispatchQueue.main.async {
                    MainActor.assumeIsolated { self.save(found, isLast: isLast) }
                }
            }
        }
    }

    private func save(_ dictations: [WisprFlow.Dictation], isLast: Bool) {
        for dictation in dictations where dictation.timestamp > lastWisprDictation {
            // Wait for the text Wispr Flow actually pasted, unless it is the last try.
            guard dictation.isFinal || isLast else { return }
            lastWisprDictation = dictation.timestamp
            lastWisprText = dictation.text
            // Dated when it reached the clipboard, even if the history was late.
            let copiedAt = lastWisprWrite
            Log.info("Saving a Wispr Flow dictation")
            deliver(RawCapture(
                representations: [CapturedRepresentation(index: 0, type: UTI.plainText, data: Data(dictation.text.utf8))],
                text: dictation.text, fileURLs: [], sourceID: WisprFlow.bundleID, sourceName: "Wispr Flow",
                isDictation: true, copiedAt: copiedAt))
        }
    }

    /// A copy made on the iPhone or another Mac (Universal Clipboard). Its
    /// data is fetched from that device on first read, so it is read away
    /// from the main thread, and only in the formats worth keeping.
    private func readRemote(changeCount count: Int) {
        remoteQueue.async { [weak self] in
            let pasteboard = DebugHooks.pasteboard
            let raw = Self.readRemoteContent(of: pasteboard)
            let unchanged = pasteboard.changeCount == count
            DispatchQueue.main.async {
                MainActor.assumeIsolated {
                    guard let self, let raw, unchanged, self.lastChangeCount == count else { return }
                    Log.info("Copy from another device (Universal Clipboard): \(raw.representations.count) formats read")
                    self.currentContent = Self.contentKey(types: [], text: raw.text)
                    self.deliver(raw)
                }
            }
        }
    }

    nonisolated private static func readRemoteContent(of pasteboard: NSPasteboard) -> RawCapture? {
        guard let item = pasteboard.pasteboardItems?.first else { return nil }
        let types = item.types.map(\.rawValue)
        let image = [UTI.png, UTI.jpeg, UTI.heic, UTI.tiff, "com.compuserve.gif"].first { types.contains($0) }
        var representations: [CapturedRepresentation] = []
        for type in [UTI.plainText, UTI.rtf, UTI.html, UTI.url] + (image.map { [$0] } ?? []) where types.contains(type) {
            guard let data = item.data(forType: NSPasteboard.PasteboardType(type)), data.count <= maxTotalSize else { continue }
            representations.append(CapturedRepresentation(index: 0, type: type, data: data))
        }
        guard !representations.isEmpty else { return nil }
        let text = representations.first { $0.type == UTI.plainText }.flatMap { String(data: $0.data, encoding: .utf8) } ?? ""
        return RawCapture(representations: representations, text: text, fileURLs: [], sourceID: nil, sourceName: nil)
    }

    /// Turns a raw copy into an item: kind, thumbnail, image size. Runs in
    /// the background. Returns nil when there is nothing worth saving.
    nonisolated static func process(_ raw: RawCapture) -> CapturedContent? {
        let representations = raw.representations
        let text = raw.text
        let fileURLs = raw.fileURLs
        let imageRep = preferredImage(in: representations)

        var content: CapturedContent
        let types = representations.map(\.type)
        // Nothing a card could show: no text format at all, no image, no file.
        let textTypes: Set<String> = [UTI.plainText, UTI.string, UTI.rtf, UTI.rtfd, UTI.html, UTI.url]
        let onlyAppData = fileURLs.isEmpty && imageRep == nil && !types.contains(where: textTypes.contains)
            && representations.contains { !$0.data.isEmpty }
        if AppContent.knownApp(in: types) != nil || onlyAppData {
            // An app's own content (Final Cut Pro clips, say): kept as is,
            // to be pasted back into it.
            let description = AppContent.describe(types: types, data: { type in
                representations.first { $0.type == type }?.data
            }, appName: raw.sourceName)
            let identity = representations.map { "\($0.index) \($0.type) \(BlobStore.hash($0.data))" }.joined(separator: "\n")
            content = CapturedContent(kind: .other, text: description, identity: identity, representations: representations)
            content.sourceBundleID = raw.sourceID
            content.sourceAppName = raw.sourceName
            return content
        }
        if !fileURLs.isEmpty {
            let paths = fileURLs.map(\.path)
            content = CapturedContent(kind: .file, text: paths.joined(separator: "\n"),
                                      identity: paths.joined(separator: "\n"), representations: representations)
            // A single image file gets a real thumbnail.
            if fileURLs.count == 1, let data = try? Data(contentsOf: fileURLs[0], options: .mappedIfSafe),
               data.count < 80 * 1024 * 1024, ImageTools.pixelSize(of: data) != nil {
                content.thumbnail = ImageTools.thumbnail(of: data)
            }
        } else if let imageRep, text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
                    || Classifier.link(text) != nil {
            // An image alone, or with just its address (Safari's Copy Image).
            var reps = representations
            // Big TIFFs (screenshots) are stored as PNG: a fraction of the size.
            if imageRep.type == UTI.tiff, imageRep.data.count > 4 * 1024 * 1024,
               !reps.contains(where: { $0.type == UTI.png }), let png = ImageTools.pngData(from: imageRep.data) {
                reps.removeAll { $0.type == UTI.tiff && $0.index == imageRep.index }
                reps.append(CapturedRepresentation(index: imageRep.index, type: UTI.png, data: png))
            }
            let size = ImageTools.pixelSize(of: imageRep.data)
            content = CapturedContent(kind: .image, text: "", identity: BlobStore.hash(imageRep.data),
                                      representations: reps, thumbnail: ImageTools.thumbnail(of: imageRep.data),
                                      imageWidth: size?.width, imageHeight: size?.height)
        } else {
            guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return nil }
            let kind = Classifier.kind(forText: text)
            let shown = kind == .text ? text : text.trimmingCharacters(in: .whitespacesAndNewlines)
            content = CapturedContent(kind: kind, text: kind == .color ? (Classifier.hexColor(text) ?? shown) : shown,
                                      identity: shown, representations: representations)
        }
        content.representations = trimmed(content.representations)
        content.sourceBundleID = raw.sourceID
        content.sourceAppName = raw.sourceName
        return content
    }

    /// Some apps copy only RTF or HTML: their text is still searchable.
    static func textFromFormatted(_ reps: [CapturedRepresentation]) -> String? {
        if let rtf = reps.first(where: { $0.type == UTI.rtf }),
           let text = NSAttributedString(rtf: rtf.data, documentAttributes: nil)?.string {
            return text
        }
        if let html = reps.first(where: { $0.type == UTI.html }),
           let text = NSAttributedString(html: html.data, documentAttributes: nil)?.string {
            return text
        }
        return nil
    }

    /// The image format worth keeping as "the" image of a copy.
    nonisolated static func preferredImage(in reps: [CapturedRepresentation]) -> CapturedRepresentation? {
        for type in [UTI.png, UTI.tiff, UTI.jpeg, UTI.heic, "public.webp", "com.compuserve.gif"] {
            if let rep = reps.first(where: { $0.type == type }) { return rep }
        }
        return nil
    }

    /// Keeps the total size reasonable: when a copy is huge, drop the
    /// heaviest secondary formats first (apps like Office put many).
    nonisolated private static func trimmed(_ reps: [CapturedRepresentation]) -> [CapturedRepresentation] {
        var total = reps.reduce(0) { $0 + $1.data.count }
        guard total > maxTotalSize else { return reps }
        let essential: Set<String> = [UTI.plainText, UTI.rtf, UTI.html, UTI.fileURL, UTI.png, UTI.url]
        var kept = reps
        for rep in reps.sorted(by: { $0.data.count > $1.data.count }) where !essential.contains(rep.type) {
            kept.removeAll { $0.index == rep.index && $0.type == rep.type }
            total -= rep.data.count
            if total <= maxTotalSize { break }
        }
        return kept
    }
}
